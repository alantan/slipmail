// Builds a provider-locked binary. Inputs come from the build environment only:
//   IMAP_HOST (required), IMAP_PORT (default 993), MAILBOX_ADDRESS (required), SCRATCH_DIR (required, absolute)
//   optional folder overrides: FOLDER_SENT, FOLDER_DRAFTS, FOLDER_ARCHIVE; OUT (default dist/slipmail)
// The values become literals in a generated entry point and baked --allow-* flags. The resulting
// binary reads none of them from its own environment or arguments.

import { validAddress } from "../src/mime_out.ts";

const HOST = /^[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$/;
// Deliberately narrow: commas would split --allow-read=a,b into several paths.
const SAFE_PATH = /^\/[A-Za-z0-9._\/+@-]*$/;

export function resolveBuildConfig(env: (k: string) => string | undefined) {
  const host = env("IMAP_HOST") ?? "";
  if (!HOST.test(host)) throw new Error("IMAP_HOST must be a plain hostname");
  const portStr = env("IMAP_PORT") ?? "993";
  const port = Number(portStr);
  if (!/^\d{1,5}$/.test(portStr) || port < 1 || port > 65535) throw new Error("IMAP_PORT must be 1-65535");
  const mailbox = env("MAILBOX_ADDRESS") ?? "";
  if (!validAddress(mailbox)) throw new Error("MAILBOX_ADDRESS is not a valid address");
  const scratchDir = (env("SCRATCH_DIR") ?? "").replace(/\/+$/, "");
  if (!SAFE_PATH.test(scratchDir) || scratchDir === "" || scratchDir.includes("..")) {
    throw new Error("SCRATCH_DIR must be an absolute path using only [A-Za-z0-9._/+@-], without '..'");
  }
  const overrides: Record<string, string> = {};
  for (
    const [k, v] of [["sent", "FOLDER_SENT"], ["drafts", "FOLDER_DRAFTS"], ["archive", "FOLDER_ARCHIVE"]]
  ) {
    const val = env(v);
    if (val) {
      // deno-lint-ignore no-control-regex
      if (/[\u0000-\u001f"\\]/.test(val)) throw new Error(`${v} contains unsupported characters`);
      if (/[^\x20-\x7e]/.test(val)) {
        throw new Error(
          `${v} must be ASCII: give the server's raw folder name (modified UTF-7 for non-ASCII names)`,
        );
      }
      overrides[k] = val;
    }
  }
  return { host, port, mailbox, scratchDir, overrides };
}

function entrySource(c: ReturnType<typeof resolveBuildConfig>): string {
  return `// GENERATED by scripts/build.ts - do not edit or commit.
import { DEFAULT_LIMITS, type BrokerConfig } from "../src/config.ts";
import { readCapped, run } from "../src/cli.ts";
import { KeychainStore } from "../src/secrets.ts";

const config: BrokerConfig = {
  host: ${JSON.stringify(c.host)},
  port: ${c.port},
  mailbox: ${JSON.stringify(c.mailbox)},
  scratchDir: ${JSON.stringify(c.scratchDir)},
  folderOverrides: ${JSON.stringify(c.overrides)},
  limits: DEFAULT_LIMITS,
};

const code = await run(Deno.args, config, {
  secrets: new KeychainStore("slipmail"),
  readStdin: (max) => readCapped(Deno.stdin.readable, max),
  write: (json) => console.log(json),
});
Deno.exit(code);
`;
}

if (import.meta.main) {
  const c = resolveBuildConfig((k) => Deno.env.get(k));
  const out = Deno.env.get("OUT") ?? "dist/slipmail";
  await Deno.mkdir("dist", { recursive: true });
  await Deno.writeTextFile("dist/entry.ts", entrySource(c));
  const flags = [
    `--allow-net=${c.host}:${c.port}`,
    // Remote-import permission defaults to a list of public CDNs; pin it to the same single endpoint.
    `--allow-import=${c.host}:${c.port}`,
    "--allow-run=/usr/bin/security",
    `--allow-read=${c.scratchDir}`,
    `--allow-write=${c.scratchDir}`,
    "--no-prompt",
  ];
  const res = await new Deno.Command("deno", {
    args: ["compile", "--config", "deno.json", ...flags, "-o", out, "dist/entry.ts"],
    stdout: "inherit",
    stderr: "inherit",
  }).output();
  if (!res.success) Deno.exit(1);
  await Deno.writeTextFile(
    "dist/build-manifest.json",
    JSON.stringify({ out, host: c.host, port: c.port, scratchDir: c.scratchDir, flags }, null, 2),
  );
  console.log(`built ${out} for ${c.host}:${c.port}`);
}
